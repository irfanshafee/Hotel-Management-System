CREATE TABLE driver (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    phone_number VARCHAR(30) NOT NULL,
    nid_number VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_driver_nid_number UNIQUE (nid_number),
    CONSTRAINT ck_driver_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_number VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    total_seats INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_vehicle_bus_number UNIQUE (bus_number),
    CONSTRAINT ck_vehicle_total_seats CHECK (total_seats > 0),
    CONSTRAINT ck_vehicle_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'MAINTENANCE'))
);

CREATE TABLE route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin VARCHAR(120) NOT NULL,
    destination VARCHAR(120) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_route_distinct_places
        CHECK (lower(trim(origin)) <> lower(trim(destination))),
    CONSTRAINT ck_route_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE UNIQUE INDEX uk_route_origin_destination
    ON route (lower(trim(origin)), lower(trim(destination)));

CREATE TABLE seat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    seat_number VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_seat_vehicle_number UNIQUE (vehicle_id, seat_number),
    CONSTRAINT fk_seat_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES vehicle (id) ON DELETE RESTRICT
);

CREATE TABLE trip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    route_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    departure_time TIMESTAMP WITH TIME ZONE NOT NULL,
    arrival_time TIMESTAMP WITH TIME ZONE NOT NULL,
    fare NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_trip_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES vehicle (id) ON DELETE RESTRICT,
    CONSTRAINT fk_trip_route FOREIGN KEY (route_id)
        REFERENCES route (id) ON DELETE RESTRICT,
    CONSTRAINT fk_trip_driver FOREIGN KEY (driver_id)
        REFERENCES driver (id) ON DELETE RESTRICT,
    CONSTRAINT uk_trip_vehicle_departure UNIQUE (vehicle_id, departure_time),
    CONSTRAINT uk_trip_driver_departure UNIQUE (driver_id, departure_time),
    CONSTRAINT ck_trip_time_range CHECK (arrival_time > departure_time),
    CONSTRAINT ck_trip_fare CHECK (fare >= 0),
    CONSTRAINT ck_trip_status
        CHECK (status IN ('SCHEDULED', 'DEPARTED', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE transport_booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    trip_id BIGINT NOT NULL,
    booking_reference UUID NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    booked_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_transport_booking_reference UNIQUE (booking_reference),
    CONSTRAINT uk_transport_booking_id_trip UNIQUE (id, trip_id),
    CONSTRAINT fk_transport_booking_trip FOREIGN KEY (trip_id)
        REFERENCES trip (id) ON DELETE RESTRICT,
    CONSTRAINT ck_transport_booking_total CHECK (total_amount >= 0),
    CONSTRAINT ck_transport_booking_status
        CHECK (status IN ('CONFIRMED', 'CANCELLED'))
);

-- trip_id is intentionally repeated here so PostgreSQL can enforce one active
-- allocation per trip and seat without querying through transport_booking.
CREATE TABLE booking_seat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    trip_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    allocation_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_booking_seat_booking_trip FOREIGN KEY (booking_id, trip_id)
        REFERENCES transport_booking (id, trip_id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_seat_seat FOREIGN KEY (seat_id)
        REFERENCES seat (id) ON DELETE RESTRICT,
    CONSTRAINT ck_booking_seat_price CHECK (price >= 0),
    CONSTRAINT ck_booking_seat_allocation_status
        CHECK (allocation_status IN ('ACTIVE', 'RELEASED'))
);

-- This is the transaction-level guard against concurrent double booking.
CREATE UNIQUE INDEX uk_booking_seat_active_trip_seat
    ON booking_seat (trip_id, seat_id)
    WHERE allocation_status = 'ACTIVE';

CREATE INDEX idx_seat_vehicle ON seat (vehicle_id);
CREATE INDEX idx_trip_route_departure_status
    ON trip (route_id, departure_time, status);
CREATE INDEX idx_trip_vehicle_departure ON trip (vehicle_id, departure_time);
CREATE INDEX idx_trip_driver_departure ON trip (driver_id, departure_time);
CREATE INDEX idx_transport_booking_user_booked
    ON transport_booking (user_id, booked_at DESC);
CREATE INDEX idx_transport_booking_trip_status
    ON transport_booking (trip_id, status);
CREATE INDEX idx_booking_seat_booking ON booking_seat (booking_id);
CREATE INDEX idx_booking_seat_seat ON booking_seat (seat_id);
