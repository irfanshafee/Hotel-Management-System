ALTER TABLE transport_booking DROP CONSTRAINT ck_transport_booking_status;
ALTER TABLE transport_booking ADD CONSTRAINT ck_transport_booking_status
    CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED'));

CREATE TABLE transport_payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_reference UUID NOT NULL,
    booking_id BIGINT NOT NULL,
    transaction_id VARCHAR(100),
    amount NUMERIC(12, 2) NOT NULL,
    paid_amount NUMERIC(12, 2) NOT NULL,
    remaining_amount NUMERIC(12, 2) NOT NULL,
    method VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_transport_payment_reference UNIQUE (payment_reference),
    CONSTRAINT uk_transport_payment_booking UNIQUE (booking_id),
    CONSTRAINT fk_transport_payment_booking FOREIGN KEY (booking_id)
        REFERENCES transport_booking (id) ON DELETE RESTRICT,
    CONSTRAINT ck_transport_payment_amounts CHECK (
        amount >= 0 AND paid_amount >= 0 AND remaining_amount >= 0),
    CONSTRAINT ck_transport_payment_method CHECK (method IN ('CARD')),
    CONSTRAINT ck_transport_payment_status CHECK (status IN ('PENDING', 'PAID', 'FAILED'))
);

CREATE UNIQUE INDEX uk_transport_payment_paid_transaction
    ON transport_payment (transaction_id)
    WHERE status = 'PAID' AND transaction_id IS NOT NULL;
